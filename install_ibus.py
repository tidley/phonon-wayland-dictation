#!/usr/bin/env python3
"""Install Phonon's Rust IBus engine for the current GNOME user (no sudo)."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
MARKER = "# Generated by Phonon IBus installer\n"
IBUS_SERVICE = "org.freedesktop.IBus.session.GNOME.service"


def write_owned(path, content):
    if path.exists() and not path.read_text().startswith(MARKER):
        raise SystemExit(f"Refusing to overwrite an unrelated configuration: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(MARKER + content)


def unit_value(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'


def install(prefix, config, binary, configure_service=False):
    helper = prefix / "libexec/phonon-ibus-helper"
    helper.parent.mkdir(parents=True, exist_ok=True)
    temporary = helper.with_suffix(".new")
    shutil.copy2(binary, temporary)
    temporary.chmod(0o755)
    temporary.replace(helper)

    components = prefix / "share/ibus/component"
    components.mkdir(parents=True, exist_ok=True)
    component = ET.Element("component")
    fields = {
        "name": "org.freedesktop.IBus.Phonon", "description": "Offline native dictation",
        "exec": f'"{str(helper).replace(chr(34), chr(92) + chr(34))}" --ibus',
        "version": "0.1.0", "author": "Phonon contributors", "license": "MIT",
        "homepage": "https://github.com/tidley/phonon-wayland-dictation",
        "textdomain": "phonon",
    }
    for key, value in fields.items():
        ET.SubElement(component, key).text = value
    engine = ET.SubElement(ET.SubElement(component, "engines"), "engine")
    for key, value in {
        "name": "phonon", "longname": "Phonon Dictation (English, UK)",
        "description": "Hold Right Ctrl to dictate directly into the focused field",
        "language": "en", "layout": "gb", "license": "MIT", "author": "Phonon contributors",
        "icon": "audio-input-microphone-symbolic", "symbol": "Ph", "rank": "0",
    }.items():
        ET.SubElement(engine, key).text = value
    ET.indent(component)
    descriptor = components / "phonon.xml"
    ET.ElementTree(component).write(descriptor, encoding="utf-8", xml_declaration=True)

    # IBus 1.5.32 does not search XDG_DATA_HOME/ibus/component by default.
    search = f"/usr/share/ibus/component:{components}"
    write_owned(config / f"systemd/user/{IBUS_SERVICE}.d/50-phonon.conf",
                f"[Service]\nEnvironment={unit_value('IBUS_COMPONENT_PATH=' + search)}\n")
    if configure_service:
        write_owned(config / "systemd/user/phonon-dictation.service.d/50-ibus.conf",
                    '[Service]\nEnvironment="PHONON_OUTPUT=auto"\n')
    return helper, descriptor


def add_source(remove=False):
    import gi
    gi.require_version("Gio", "2.0")
    from gi.repository import Gio, GLib
    settings = Gio.Settings.new("org.gnome.desktop.input-sources")
    sources = settings.get_value("sources").unpack()
    source = ("ibus", "phonon")
    if remove:
        sources = [tuple(item) for item in sources if tuple(item) != source]
        if not sources:
            raise SystemExit("Select another keyboard source before uninstalling Phonon")
    elif source not in [tuple(item) for item in sources]:
        sources.append(source)
    settings.set_value("sources", GLib.Variant("a(ss)", sources))
    Gio.Settings.sync()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--configure-service", action="store_true", help="Enable automatic IBus/clipboard routing in the existing dictation service")
    parser.add_argument("--add-source", action="store_true", help="Add Phonon to GNOME's input menu, retaining other sources")
    parser.add_argument("--refresh", action="store_true", help="Restart GNOME IBus to discover the new engine; restart dictation if configured")
    parser.add_argument("--no-build", action="store_true", help="Use an already built release binary")
    parser.add_argument("--uninstall", action="store_true", help="Remove this install and its GNOME source (does not remove the speech app)")
    args = parser.parse_args()
    prefix = Path.home() / ".local"
    config = Path(os.getenv("XDG_CONFIG_HOME", str(Path.home() / ".config")))
    if args.uninstall:
        add_source(remove=True)
        for path in (prefix / "libexec/phonon-ibus-helper", prefix / "share/ibus/component/phonon.xml"):
            path.unlink(missing_ok=True)
        for path in (config / f"systemd/user/{IBUS_SERVICE}.d/50-phonon.conf",
                     config / "systemd/user/phonon-dictation.service.d/50-ibus.conf"):
            if path.exists() and path.read_text().startswith(MARKER):
                path.unlink()
        print("Removed Phonon IBus installation; clipboard dictation is retained.")
        search = "/usr/share/ibus/component"
    else:
        if not args.no_build:
            subprocess.run(["cargo", "build", "--release", "--locked", "--manifest-path",
                            str(ROOT / "rust/ibus-helper/Cargo.toml")], check=True)
        helper, descriptor = install(prefix, config, ROOT / "rust/ibus-helper/target/release/phonon-ibus-helper", args.configure_service)
        search = f"/usr/share/ibus/component:{descriptor.parent}"
        print(f"Installed helper: {helper}\nInput-method descriptor: {descriptor}")
    # An old user registry cache may not know to watch the new component path.
    subprocess.run(["ibus", "write-cache"], env={**os.environ, "IBUS_COMPONENT_PATH": search}, check=True)
    subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
    if args.refresh:
        subprocess.run(["systemctl", "--user", "restart", IBUS_SERVICE], check=True)
    if args.add_source and not args.uninstall:
        add_source()
    if args.refresh and (args.configure_service or args.uninstall):
        subprocess.run(["systemctl", "--user", "restart", "phonon-dictation.service"], check=True)
    if not args.uninstall:
        print("Select Phonon Dictation (English, UK) with Super+Space or the GNOME input-source menu.")
        if not args.refresh:
            print("Log out and back in for IBus discovery, or rerun with --no-build --refresh when idle.")


if __name__ == "__main__":
    main()
